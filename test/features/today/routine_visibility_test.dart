// TODAY (D-044) — the routine-visibility fix as a widget:
// routines created AFTER today's plan was generated no longer
// vanish silently. The Daily To-do section renders with the
// explanation and the explicit Add to today's plan action;
// tapping it inserts the routines into the existing plan.
// Harness mirrors plan_sheet_test.dart.
import 'dart:io';

import 'package:daily_life_app/core/db/app_database.dart';
import 'package:daily_life_app/core/theme.dart';
import 'package:daily_life_app/features/goals/goals_store.dart';
import 'package:daily_life_app/features/items/link_card/thumbnail_service.dart';
import 'package:daily_life_app/features/learn/learn_services.dart';
import 'package:daily_life_app/features/learn/learn_store.dart';
import 'package:daily_life_app/features/learn/library_store.dart';
import 'package:daily_life_app/features/review/review_store.dart';
import 'package:daily_life_app/features/store.dart';
import 'package:daily_life_app/features/today/today_screen.dart';
import 'package:daily_life_app/features/today/today_store.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:sqflite_common_ffi/sqflite_ffi.dart';

void main() {
  setUpAll(() {
    sqfliteFfiInit();
    databaseFactory = databaseFactoryFfi;
  });

  Future<void> waitFor(WidgetTester tester, Finder f) async {
    for (var i = 0; i < 60; i++) {
      if (f.evaluate().isNotEmpty) return;
      await Future<void>.delayed(const Duration(milliseconds: 60));
      await tester.pump(const Duration(milliseconds: 60));
    }
    fail('Timed out waiting for $f');
  }

  testWidgets('late-created routines are explained, then added '
      'explicitly', (tester) async {
    await tester.runAsync(() async {
      tester.view.physicalSize = const Size(800, 1700);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.reset);
      final tmp = await Directory.systemTemp.createTemp('nimo-vis-');
      final db = await AppDatabase.openFile('${tmp.path}/test.db');
      final store = Store(db);
      final todayStore = TodayStore(db);
      final library = LibraryStore(Directory('${tmp.path}/Library'));
      await library.ensureLayout();

      // The user's exact situation: today's plan generated by
      // the first one-off; the routines created afterwards.
      final today = DateTime.now();
      await todayStore.addOneOff(today, 'Watch a video');
      await todayStore.addTemplate('Go to Hospital');
      await todayStore.addTemplate('Go to run');

      await tester.pumpWidget(MaterialApp(
        theme: AppTheme.neoDark(),
        home: TodayScreen(
          store: store,
          todayStore: todayStore,
          goalsStore: GoalsStore(db),
          reviewStore: ReviewStore(db, todayStore),
          learn: LearnServices(LearnStore(db), library, db: db),
          thumbnails:
              ThumbnailService(Directory('${tmp.path}/thumbs')),
          onOpenTopics: () {},
          onOpenWorkspace: (_) {},
          onOpenLearn: () {},
          onOpenSettings: () {},
          onOpenProgress: () {},
        ),
      ));

      // The section renders WITH the explanation (previously it
      // vanished entirely).
      await waitFor(tester, find.text('DAILY TO-DO'));
      await waitFor(
          tester, find.textContaining('start tomorrow'));
      await waitFor(tester, find.text("Add to today's plan"));
      // The routines are not silently in the plan yet.
      final before = await todayStore.planItems(today);
      expect(before.where((i) => i.isRoutine), isEmpty);

      await tester.tap(find.text("Add to today's plan"));
      await waitFor(tester, find.text('Go to Hospital'));
      await waitFor(tester, find.text('Go to run'));

      final after = await todayStore.planItems(today);
      expect(
          after.where((i) => i.isRoutine).map((i) => i.title),
          containsAll(['Go to Hospital', 'Go to run']));
      expect(after.singleWhere((i) => i.title == 'Watch a video').done,
          isFalse);
      await db.close();
      await tmp.delete(recursive: true);
    });
  });
}
